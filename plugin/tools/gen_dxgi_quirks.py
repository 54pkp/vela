"""Writes py_modules/dxgi_quirks.py: the games whose OptiScaler quirk turns DXGI spoofing off (GameQuirk::DisableDxgiSpoofing).

Why: the fork applies that quirk only when OptiScaler.ini has no Dxgi value (dllmain.cpp: `quirks & DisableDxgiSpoofing &&
!DxgiSpoofing.has_value()`), and sgsr3.ini_values() writes Dxgi=true for every game, so the quirk was dropped (report 9NPQFQ,
Returnal). With this list ini_values() writes Dxgi=false for those exes, the value the quirk itself sets. Not "auto": "auto" also
lets the fork switch spoofing off when no nvngx.dll is found (dllmain.cpp ~2073), and the kit ships none.

The list must come from the Quirks.h the shipped DLL is built from: the base commit named in assets/sgsr3/VERSION.json
"source" (Sloptiscaler <commit>). Patch 0000 (upstream sync) is the only fork patch that changes Quirks.h; while it is not in
the build, the base's header is the shipped one.

  python tools/gen_dxgi_quirks.py                   # header from the fork repo at the VERSION.json base (VELA_OPTI_REPO,
                                                    # default C:/src/ext/vela7/opti, git show <base>:OptiScaler/misc/Quirks.h)
  python tools/gen_dxgi_quirks.py --header <file>   # a header file instead (label it with --base)
tests/test_dxgi_quirks.py fails when the list no longer matches VERSION.json's base or the header.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "py_modules", "dxgi_quirks.py")
VERSION_JSON = os.path.join(ROOT, "assets", "sgsr3", "VERSION.json")
DEFAULT_REPO = "C:/src/ext/vela7/opti"
HEADER_PATH = "OptiScaler/misc/Quirks.h"
FLAG = "DisableDxgiSpoofing"


def build_base():
    """(base commit, patches) of the shipped DLL, from VERSION.json."""
    with open(VERSION_JSON, encoding="utf-8") as f:
        v = json.load(f)
    m = re.search(r"Sloptiscaler ([0-9a-f]{7,40})", v.get("source", ""))
    if not m:
        raise SystemExit("VERSION.json 'source' names no 'Sloptiscaler <commit>'")
    return m.group(1), list(v.get("patches") or [])


def header_at(repo, base):
    """bytes of Quirks.h at <base> in the fork repo, or None when the repo / commit is not here."""
    try:
        return subprocess.run(["git", "-c", "safe.directory=*", "-C", repo, "show", f"{base}:{HEADER_PATH}"],
                              capture_output=True, check=True, timeout=60).stdout
    except (OSError, subprocess.SubprocessError):
        return None


def _strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def parse(header_bytes):
    """(entries, exes): the quirkTable entries carrying DisableDxgiSpoofing and their exe names (lower case; a
    QUIRK_ENTRY_UE(name) gives name-win64-shipping.exe and name-wingdk-shipping.exe, as the macro does)."""
    text = _strip_comments(header_bytes.decode("utf-8", "replace"))
    start = text.find("quirkTable[]")
    if start < 0:
        raise ValueError("no quirkTable[] in the header")
    end = text.find("};", start)
    table = text[start:end]
    entries, exes = 0, set()
    for m in re.finditer(r"\bQUIRK_ENTRY(_UE)?\s*\(", table):
        i, depth = m.end(), 1
        while depth and i < len(table):
            depth += {"(": 1, ")": -1}.get(table[i], 0)
            i += 1
        args = [a.strip() for a in table[m.end():i - 1].split(",")]
        if FLAG not in {a.split("::")[-1] for a in args[1:]}:
            continue
        entries += 1
        name = args[0]
        if m.group(1):
            exes.update({f"{name}-win64-shipping.exe".lower(), f"{name}-wingdk-shipping.exe".lower()})
        else:
            exes.add(name.strip('"').lower())
    return entries, exes


def render(base, sha1, entries, exes):
    lines = [
        '"""GENERATED by tools/gen_dxgi_quirks.py, do not edit: the exes whose OptiScaler quirk turns DXGI spoofing off',
        f"(GameQuirk::DisableDxgiSpoofing, {HEADER_PATH} at Sloptiscaler {base}, the base of the shipped DLL).",
        "sgsr3.ini_values() writes Spoofing.Dxgi=false for them, the value the quirk sets (our Dxgi=true would cancel it);",
        'a profiles.py "ini" still wins (Control keeps true). tests/test_dxgi_quirks.py checks it against VERSION.json."""',
        "import os",
        "",
        f'BASE = "{base}"',
        f'SOURCE_SHA1 = "{sha1}"',
        f"ENTRIES = {entries}",
        "EXES = frozenset({",
    ]
    lines += [f'    "{e}",' for e in sorted(exes)]
    lines += [
        "})",
        "",
        "",
        "def disables_dxgi(exe):",
        '    """True when OptiScaler turns DXGI spoofing off for this game binary (name or path, any case)."""',
        "    return bool(exe) and os.path.basename(str(exe).replace(\"\\\\\", \"/\")).lower() in EXES",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=os.environ.get("VELA_OPTI_REPO", DEFAULT_REPO))
    ap.add_argument("--header", help="a Quirks.h file instead of the repo")
    ap.add_argument("--base", help="label for --header (default: the VERSION.json base)")
    a = ap.parse_args()
    base, patches = build_base()
    if "0000" in patches and not a.header:
        raise SystemExit("patch 0000 (upstream sync, changes Quirks.h) is in the DLL build: pass the patched header with --header")
    if a.header:
        with open(a.header, "rb") as f:
            data = f.read()
        base = a.base or base
    else:
        data = header_at(a.repo, base)
        if data is None:
            raise SystemExit(f"no {HEADER_PATH} at {base} in {a.repo}")
    entries, exes = parse(data)
    if not entries:
        raise SystemExit("no DisableDxgiSpoofing entries parsed")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(base, hashlib.sha1(data).hexdigest(), entries, exes))
    print(f"{OUT}: {entries} entries, {len(exes)} exes, base {base}")


if __name__ == "__main__":
    sys.exit(main())
